import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { QRCodeSVG } from "qrcode.react";
import sharp from "sharp";
import { describe, expect, it } from "vitest";
import { decodeQrFromPixels } from "@/lib/qr/decode";
import { classifyQrPayload } from "@/lib/qr/payload";

async function pixelsFor(svg: string) {
  const { data, info } = await sharp(Buffer.from(svg)).resize(400, 400).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  return { data: new Uint8ClampedArray(data.buffer, data.byteOffset, data.byteLength), w: info.width, h: info.height };
}

describe("QR decode", () => {
  it("round-trips a QR generated by qrcode.react", async () => {
    const url = "https://alight.link/abcXYZ123";
    const svg = renderToStaticMarkup(createElement(QRCodeSVG, { value: url, size: 400, marginSize: 4, level: "M" }));
    const { data, w, h } = await pixelsFor(svg);
    expect(decodeQrFromPixels(data, w, h)).toBe(url);
  });
  it("returns null for an image without a QR", () => {
    const w = 64, h = 64;
    expect(decodeQrFromPixels(new Uint8ClampedArray(w * h * 4).fill(255), w, h)).toBeNull();
  });
  it("returns null for inconsistent dimensions", () => {
    expect(decodeQrFromPixels(new Uint8ClampedArray(10), 10, 10)).toBeNull();
  });
});

describe("classifyQrPayload", () => {
  it("accepts known preset links", () => {
    const r = classifyQrPayload("https://www.capcut.com/t/Zs8abc/");
    expect(r.kind).toBe("url");
    if (r.kind === "url") expect(r.link).toMatchObject({ known: true, platform: "capcut" });
  });
  it("flags unknown domains but allows them with confirmation", () => {
    const r = classifyQrPayload("https://example.org/x");
    expect(r.kind === "url" && r.link.known).toBe(false);
  });
  it.each(["javascript:alert(1)", "intent://x#Intent;end", "file:///etc/passwd", "http://192.168.1.1/", "http://localhost/"])("never opens %s", (p) => {
    expect(classifyQrPayload(p).kind).toBe("unsafe_url");
  });
  it("treats plain text as text", () => {
    expect(classifyQrPayload("halo dunia").kind).toBe("text");
  });
});
